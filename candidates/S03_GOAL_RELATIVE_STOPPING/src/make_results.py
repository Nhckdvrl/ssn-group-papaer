"""S03 — regenerate every headline table in docs/RESULTS.md from raw results."""
import json, math, os, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(HERE)
PY = sys.executable


def run(script, *args):
    return subprocess.run([PY, f"src/{script}", *args],
                          capture_output=True, text=True).stdout


def seeds(tmpl, ss=("0", "1")):
    ps = [tmpl.format(s=s) for s in ss]
    return ",".join(p for p in ps if os.path.exists(p))


ARM0 = "results/e02/arm0_samepath/e01.jsonl"
NAT = "results/e01/olmo3-7b_sft_eosonly.jsonl"

blocks = []

blocks.append(("Layer B — natural post-training trajectory (format-matched)",
               run("e01_decompose.py",
                   "results/e01/olmo3-7b_base_plain.jsonl",
                   "results/e01/olmo3-7b_sft_plain.jsonl",
                   "results/e01/olmo3-7b_dpo_plain.jsonl",
                   "results/e01/olmo3-7b_instruct_plain.jsonl")))

specs = [f"Arm0={ARM0}"]
for arm in ("R", "Rmlp"):
    specs.append(f"{arm}@750=" + seeds(f"results/e02/final/{arm}_s{{s}}/e01.jsonl"))
for arm, st in (("R", 250), ("R", 2250), ("Sbody", 250), ("Sbody", 750),
                ("Sbody", 2250), ("S", 250), ("S", 2250), ("F", 250), ("F", 2250)):
    p = seeds(f"results/e02/budget/{arm}_st{st}_s{{s}}/e01.jsonl")
    if p:
        specs.append(f"{arm}@{st}={p}")
for arm in ("S", "F"):
    specs.append(f"{arm}@750=" + seeds(f"results/e02/final/{arm}_s{{s}}/e01.jsonl"))
specs.append(f"natSFT={NAT}")
specs = [s for s in specs if s.split("=", 1)[1]]
blocks.append(("Layer C — parameter-locus arms, all gauges",
               run("e01_rawlogit.py", *specs)))

blocks.append(("Layer C — paired contrasts against Arm 0",
               run("e01_rawlogit.py", *specs, "--vs", "Arm0",
                   "--metrics", "dz_stop", "dz_cont", "d_goal")))

for st in (250, 750, 2250):
    blocks.append((f"Three-family parameter-locus replication @ {st} steps",
                   run("e02_threefamily.py", str(st))))

blocks.append(("External lineages — architecture test (native chat format)",
               run("e01_external.py",
                   "Qwen2.5 base (grafted)=results/e01/qwen2.5-7b_base_grafted.jsonl",
                   "Qwen2.5 Instruct=results/e01/qwen2.5-7b_instruct.jsonl",
                   "Llama-3.1 base (grafted)=results/e01/llama3.1-8b_base_grafted.jsonl",
                   "Llama-3.1 Instruct=results/e01/llama3.1-8b_instruct.jsonl")))

with open("docs/RESULTS.md", "w") as fh:
    fh.write("# S03 — evidence spine\n\n")
    fh.write("Regenerated by `src/make_results.py`; every number below comes\n"
             "from the raw per-item files in `results/`. Do not hand-edit.\n\n")
    fh.write("Primary decision position `p2`; `d_goal` is the gauge-free margin\n"
             "shift, `dz_stop` the raw stop-logit shift, `dz_cont` the raw\n"
             "continuation-logit shift, and `d_stop` the probability-gauge\n"
             "version that carries a whole-vocabulary normalizer term.\n\n")
    for title, body in blocks:
        fh.write(f"\n## {title}\n\n```\n{body.strip()}\n```\n")
print("wrote docs/RESULTS.md")
