"""Data for Figure 1 (paper/figures/fig_overview.tex).

Reads the E132 accuracies stored by paper_figures_v2.py in paper/figures/numbers.json
(SST-5, shared label words, conflicting conventions, confirmation split, 32 prompts per model)
and writes paper/figures/fig_overview_data.tex with the per-model values and their mean.
"""
import json
from pathlib import Path

FIG = Path(__file__).resolve().parents[1] / 'paper' / 'figures'
acc = {m: v['acc'] for m, v in json.loads((FIG / 'numbers.json').read_text())['e132_summary'].items()}
ROWS = {'Native': 'shared_normal_native', 'Isolated': 'shared_all_cross_off_native',
        'Names': 'shared_iso_names_native', 'Selective': 'shared_answer_cross_off_native'}
lines = ['% Generated by scripts/fig_overview_data.py from numbers.json (E132); do not edit.']
for name, key in ROWS.items():
    vals = [acc[m][key]['mean'] for m in acc]
    lines.append(f'\\def\\acc{name}{{{",".join(f"{v:.1f}" for v in vals)}}}')
    lines.append(f'\\def\\mean{name}{{{sum(vals) / len(vals):.1f}}}')
(FIG / 'fig_overview_data.tex').write_text('\n'.join(lines) + '\n')
print('\n'.join(lines))
