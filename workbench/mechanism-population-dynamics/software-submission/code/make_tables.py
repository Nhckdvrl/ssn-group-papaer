def tab_critical():
    d = json.loads((R / "controlled" / "analysis.json").read_text())
    controlled_pairs = json.loads((R / "controlled_corpus_pairs.json").read_text())
    L = json.loads((R / "controlled_large_model.json").read_text())

    def arm(pat):
        pts = {}
        for k, v in d["D"].items():
            mm = re.search(r"_b(\d+)_", k)
            if mm and re.search(pat, k):
                pts.setdefault(int(mm.group(1)), []).append(np.mean([v[m][1] for m in ("M1", "M2") if m in v]))
        return pts
    code, n1, n01 = arm("tocode"), arm("eps1$"), arm("eps0.1$")
    c0 = lambda eps: [np.mean([v[m][1] for m in ("M1", "M2") if m in v]) for k, v in d["C"].items() if k.endswith(f"_eps{eps}")]
    code[0] = [np.mean([controlled_pairs[m]["SI_code"] for m in ("M1", "M2")])]
    n1[0], n01[0] = c0("1"), c0("0.1")
    big = {0: L["L_i1_code_o1"], 100: L["L_i1_c4_o1_b100_tocode_too300"], 1000: L["L_i1_c4_o1_b1000_tocode_too1200"]}
