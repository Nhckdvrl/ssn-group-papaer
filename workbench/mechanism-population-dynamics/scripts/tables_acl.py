MINUS = "$-$"


def f2(v, signed=False):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "--"
    if round(v, 2) == 0:
        v = 0.0
    s = f"{v:+.2f}" if signed else f"{v:.2f}"
    return s.replace("-", MINUS) if s.startswith("-") else s


def write(name, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text("% generated by scripts/tables_acl.py -- do not edit by hand\n" + body)


